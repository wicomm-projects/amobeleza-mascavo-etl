-- PROVISÓRIO: escrito a partir do dicionário da WPP ("Documentação Amobeleza", seção 2.5, p. 30–31) até o schema:pull trazer o
-- SHOW CREATE TABLE real da produção. Índices: as colunas marcadas IDX no dicionário, com nomes no padrão do Laravel.
-- PK = id do pedido no AnyMarket (sem AUTO_INCREMENT). Valores em reais; datas em UTC.
CREATE TABLE `anymarket_orders` (
  `id` bigint unsigned NOT NULL,
  `account_name` varchar(255) NOT NULL,
  `market_place_id` varchar(255) NOT NULL,
  `market_place_number` varchar(255) NOT NULL,
  `market_place` varchar(255) NOT NULL,
  `order_created_at` timestamp NOT NULL,
  `payment_date` timestamp NULL DEFAULT NULL,
  `transmission_status` varchar(255) NOT NULL,
  `status` varchar(255) NOT NULL,
  `invoice_access_key` varchar(255) DEFAULT NULL,
  `invoice_series` varchar(255) DEFAULT NULL,
  `invoce_number` varchar(255) DEFAULT NULL,
  `invoice_date` timestamp NULL DEFAULT NULL,
  `market_place_status` varchar(255) NOT NULL,
  `discount` decimal(8,2) NOT NULL,
  `freight` decimal(8,2) NOT NULL,
  `seller_freight` decimal(8,2) NOT NULL,
  `interest_value` decimal(8,2) NOT NULL,
  `gross` decimal(8,2) NOT NULL,
  `total` decimal(8,2) NOT NULL,
  `deliver_status` varchar(255) NOT NULL,
  `id_account` int NOT NULL,
  `fulfillment` tinyint(1) NOT NULL,
  `meta_data_need_invoice_xml` tinyint(1) DEFAULT NULL,
  `meta_data_fiscal_document_file_type` varchar(255) DEFAULT NULL,
  `meta_data_system_origin` varchar(255) DEFAULT NULL,
  `meta_data_shipping_type_to_send` varchar(255) DEFAULT NULL,
  `order_type_name` varchar(255) DEFAULT NULL,
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `anymarket_orders_account_name_index` (`account_name`),
  KEY `anymarket_orders_market_place_index` (`market_place`),
  KEY `anymarket_orders_order_created_at_index` (`order_created_at`),
  KEY `anymarket_orders_payment_date_index` (`payment_date`),
  KEY `anymarket_orders_status_index` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
